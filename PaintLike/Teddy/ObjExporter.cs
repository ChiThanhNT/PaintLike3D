using System;
using System.Collections.Generic;
using System.Drawing;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Numerics;
using System.Text;

namespace PaintLike.Teddy
{
    /// <summary>
    /// [TV3-04] Xuất và Nhập mô hình 3D theo định dạng chuẩn Wavefront .OBJ (Mục 6 bài báo Teddy SIGGRAPH '99).
    /// </summary>
    public static class ObjExporter
    {
        public static void SaveToFile(TeddyMesh mesh, string filePath)
        {
            SaveToFile(new[] { mesh }, filePath);
        }

        public static void SaveToFile(IReadOnlyList<TeddyMesh> meshes, string filePath)
        {
            if (meshes == null || meshes.Count == 0 || !meshes.Any(m => m != null && !m.IsEmpty))
                throw new InvalidOperationException("Không có dữ liệu lưới 3D để xuất ra file .OBJ.");

            var sb = new StringBuilder();
            var mtlSb = new StringBuilder();
            var inv = CultureInfo.InvariantCulture;

            string mtlPath = Path.ChangeExtension(filePath, ".mtl");
            string mtlFileName = Path.GetFileName(mtlPath);

            sb.AppendLine("# Exported from PaintLike Studio - Teddy 3D Freeform Modeler (ACM SIGGRAPH '99)");
            sb.AppendLine($"# Objects: {meshes.Count(m => m != null && !m.IsEmpty)}");
            sb.AppendLine($"mtllib {mtlFileName}");

            mtlSb.AppendLine("# Material library generated by PaintLike Studio (Teddy 3D - Hình 2 Multi-Color Support)");
            var definedMaterials = new Dictionary<int, string>();

            string EnsureMaterial(Color c)
            {
                int argb = Color.FromArgb(255, c.R, c.G, c.B).ToArgb();
                if (definedMaterials.TryGetValue(argb, out string? existingName))
                    return existingName;

                string matName = $"mat_{c.R}_{c.G}_{c.B}";
                definedMaterials[argb] = matName;

                mtlSb.AppendLine($"newmtl {matName}");
                mtlSb.AppendLine(string.Format(inv, "Ka {0:F4} {1:F4} {2:F4}", c.R / 255f * 0.25f, c.G / 255f * 0.25f, c.B / 255f * 0.25f));
                mtlSb.AppendLine(string.Format(inv, "Kd {0:F4} {1:F4} {2:F4}", c.R / 255f, c.G / 255f, c.B / 255f));
                mtlSb.AppendLine("Ks 0.1200 0.1200 0.1200");
                mtlSb.AppendLine("Ns 32.0");
                mtlSb.AppendLine("d 1.0");
                mtlSb.AppendLine("illum 2");
                mtlSb.AppendLine();
                return matName;
            }

            int vOffset = 0;
            int objIndex = 1;

            foreach (var mesh in meshes)
            {
                if (mesh == null || mesh.IsEmpty) continue;
                mesh.RecalculateNormals();

                sb.AppendLine($"o Object_{objIndex++}");

                foreach (Vector3 v in mesh.Vertices)
                {
                    sb.AppendLine(string.Format(inv, "v {0:F4} {1:F4} {2:F4}", v.X, v.Y, v.Z));
                }

                foreach (Vector3 vn in mesh.VertexNormals)
                {
                    sb.AppendLine(string.Format(inv, "vn {0:F4} {1:F4} {2:F4}", vn.X, vn.Y, vn.Z));
                }

                string? lastMat = null;
                foreach (var tri in mesh.Triangles)
                {
                    Color faceCol = tri.CustomColor ?? mesh.BaseColor;
                    string matName = EnsureMaterial(faceCol);
                    if (matName != lastMat)
                    {
                        sb.AppendLine($"usemtl {matName}");
                        lastMat = matName;
                    }

                    int i0 = tri.V0 + 1 + vOffset;
                    int i1 = tri.V1 + 1 + vOffset;
                    int i2 = tri.V2 + 1 + vOffset;
                    sb.AppendLine($"f {i0}//{i0} {i1}//{i1} {i2}//{i2}");
                }

                vOffset += mesh.Vertices.Count;
            }

            File.WriteAllText(mtlPath, mtlSb.ToString(), Encoding.UTF8);
            File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
        }

        public static TeddyMesh LoadFromFile(string filePath)
        {
            var mesh = new TeddyMesh
            {
                BaseColor = Color.FromArgb(244, 162, 97)
            };

            var inv = CultureInfo.InvariantCulture;
            string[] lines = File.ReadAllLines(filePath, Encoding.UTF8);
            string baseDir = Path.GetDirectoryName(filePath) ?? "";

            var materials = new Dictionary<string, Color>(StringComparer.OrdinalIgnoreCase);
            Color? activeColor = null;
            var colorHistogram = new Dictionary<int, (Color Col, int Count)>();

            foreach (string rawLine in lines)
            {
                string line = rawLine.Trim();
                if (string.IsNullOrEmpty(line) || line.StartsWith("#"))
                    continue;

                string[] parts = line.Split(new char[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
                if (parts.Length == 0) continue;

                if (parts[0] == "mtllib" && parts.Length >= 2)
                {
                    string mtlName = line.Substring(6).Trim();
                    string mtlFullPath = Path.IsPathRooted(mtlName) ? mtlName : Path.Combine(baseDir, mtlName);
                    if (File.Exists(mtlFullPath))
                    {
                        ParseMtlFile(mtlFullPath, materials, inv);
                    }
                }
                else if (parts[0] == "usemtl" && parts.Length >= 2)
                {
                    string matName = parts[1];
                    activeColor = materials.TryGetValue(matName, out Color mc) ? mc : (Color?)null;
                }
                else if (parts[0] == "v" && parts.Length >= 4)
                {
                    if (float.TryParse(parts[1], NumberStyles.Float, inv, out float x) &&
                        float.TryParse(parts[2], NumberStyles.Float, inv, out float y) &&
                        float.TryParse(parts[3], NumberStyles.Float, inv, out float z))
                    {
                        mesh.Vertices.Add(new Vector3(x, y, z));
                    }
                }
                else if (parts[0] == "f" && parts.Length >= 4)
                {
                    var faceIndices = new List<int>();
                    for (int i = 1; i < parts.Length; i++)
                    {
                        string token = parts[i].Split('/')[0];
                        if (int.TryParse(token, NumberStyles.Integer, inv, out int objIdx))
                        {
                            int zeroIdx = objIdx > 0 ? objIdx - 1 : mesh.Vertices.Count + objIdx;
                            if (zeroIdx >= 0 && zeroIdx < mesh.Vertices.Count)
                                faceIndices.Add(zeroIdx);
                        }
                    }

                    // Chia quạt tam giác nếu mặt có >= 3 đỉnh và giữ nguyên màu vùng CustomColor từ .MTL
                    for (int i = 1; i < faceIndices.Count - 1; i++)
                    {
                        var tri = new TeddyTriangle(faceIndices[0], faceIndices[i], faceIndices[i + 1])
                        {
                            CustomColor = activeColor
                        };
                        mesh.Triangles.Add(tri);

                        if (activeColor.HasValue)
                        {
                            int argb = activeColor.Value.ToArgb();
                            if (colorHistogram.TryGetValue(argb, out var entry))
                                colorHistogram[argb] = (entry.Col, entry.Count + 1);
                            else
                                colorHistogram[argb] = (activeColor.Value, 1);
                        }
                    }
                }
            }

            if (colorHistogram.Count > 0)
            {
                Color dominant = colorHistogram.Values.OrderByDescending(x => x.Count).First().Col;
                mesh.BaseColor = dominant;
            }

            // Tự động căn tâm và chuẩn hóa kích thước nếu mô hình bên ngoài quá nhỏ hoặc quá lớn
            NormalizeLoadedMesh(mesh, 150f);
            mesh.BuildConnectivity();
            mesh.RecalculateNormals();
            return mesh;
        }

        private static void ParseMtlFile(string mtlPath, Dictionary<string, Color> outMaterials, CultureInfo inv)
        {
            string? currentMat = null;
            foreach (string rawLine in File.ReadAllLines(mtlPath, Encoding.UTF8))
            {
                string line = rawLine.Trim();
                if (string.IsNullOrEmpty(line) || line.StartsWith("#")) continue;

                string[] parts = line.Split(new char[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
                if (parts.Length == 0) continue;

                if (parts[0] == "newmtl" && parts.Length >= 2)
                {
                    currentMat = parts[1];
                }
                else if (parts[0] == "Kd" && parts.Length >= 4 && !string.IsNullOrEmpty(currentMat))
                {
                    if (float.TryParse(parts[1], NumberStyles.Float, inv, out float r) &&
                        float.TryParse(parts[2], NumberStyles.Float, inv, out float g) &&
                        float.TryParse(parts[3], NumberStyles.Float, inv, out float b))
                    {
                        outMaterials[currentMat] = Color.FromArgb(
                            Math.Clamp((int)MathF.Round(r * 255f), 0, 255),
                            Math.Clamp((int)MathF.Round(g * 255f), 0, 255),
                            Math.Clamp((int)MathF.Round(b * 255f), 0, 255));
                    }
                }
            }
        }

        private static void NormalizeLoadedMesh(TeddyMesh mesh, float targetRadius)
        {
            if (mesh.Vertices.Count == 0) return;

            Vector3 min = mesh.Vertices[0];
            Vector3 max = mesh.Vertices[0];
            foreach (var v in mesh.Vertices)
            {
                min = Vector3.Min(min, v);
                max = Vector3.Max(max, v);
            }

            Vector3 center = 0.5f * (min + max);
            float maxExtent = MathF.Max(max.X - min.X, MathF.Max(max.Y - min.Y, max.Z - min.Z)) * 0.5f;
            float scale = maxExtent > 1e-4f ? targetRadius / maxExtent : 1f;

            for (int i = 0; i < mesh.Vertices.Count; i++)
            {
                mesh.Vertices[i] = (mesh.Vertices[i] - center) * scale;
            }
        }
    }
}
